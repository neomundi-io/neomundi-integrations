def _render_quickstart(active: list[Integration], *, fr: bool) -> str:
    if not active:
        return ""
    first = active[0]
    snippet = (first.data.get("entrypoint") or {}).get("snippet", "").rstrip()
    title = "## Démarrer en trois lignes" if fr else "## Start in three lines"
    lead = (
        f"Avec **{first.name}**. Chaque intégration suit la même forme : construire le "
        f"gestionnaire, le passer en rappel, lire l'issue."
        if fr
        else f"With **{first.name}**. Every integration follows the same shape: build the "
        f"handler, pass it as a callback, read the outcome."
    )
    note = (
        "Ce paquet n'est pas encore publié sur PyPI. Installation depuis le dépôt :"
        if not first.is_published and fr
        else (
            "This package is not published on PyPI yet. Install from the repository:"
            if not first.is_published
            else ""
        )
    )
    install_block = (
        f"\n{note}\n\n```bash\n{first.install_line}\n```\n"
        if note
        else (f"\n```bash\n{first.install_line}\n```\n")
    )
    more = (
        f"\n[Guide complet de {first.name} →]({first.rel_dir}/README_FR.md)\n"
        if fr
        else f"\n[Full {first.name} guide →]({first.rel_dir}/README.md)\n"
    )
    return f"{title}\n\n{lead}\n{install_block}\n```python\n{snippet}\n```\n{more}"


