# --------------------------------------------------------------------- badges


def render_badges(active: list[Integration], archived: list[Integration]) -> dict[str, str]:
    """Shields.io endpoint files, so a badge reflects the registry.

    A badge that is typed by hand becomes a lie within a month. These are
    generated, consumed as
    ``shields.io/endpoint?url=.../badges/<name>.json``.
    """
    counts = as_json(active, archived)["counts"]
    out: dict[str, str] = {
        "library.json": json.dumps(
            {
                "schemaVersion": 1,
                "label": "integrations",
                "message": str(counts["active"]),
                "color": "0f766e",
            }
        ),
        "evidence.json": json.dumps(
            {
                "schemaVersion": 1,
                "label": "evidence E2+",
                "message": f"{counts['evidence_e2_or_better']}/{counts['active']}",
                "color": "0f766e" if counts["evidence_e2_or_better"] else "9ca3af",
            }
        ),
    }
    for integration in active:
        maturity_text, maturity_colour = MATURITY_STYLE.get(
            integration.maturity, (integration.maturity, "9ca3af")
        )
        out[f"{integration.slug}-maturity.json"] = json.dumps(
            {
                "schemaVersion": 1,
                "label": integration.name.lower(),
                "message": maturity_text,
                "color": maturity_colour,
            }
        )
        out[f"{integration.slug}-evidence.json"] = json.dumps(
            {
                "schemaVersion": 1,
                "label": "evidence",
                "message": integration.evidence_level.upper(),
                "color": EVIDENCE_COLOR.get(integration.evidence_level, "9ca3af"),
            }
        )
    return out


# ----------------------------------------------------------------------- main


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any file is stale")
    args = parser.parse_args()

    try:
        active, archived = load_all()
    except RegistryError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 1

    rendered: dict[Path, str] = {
        ROOT / "README.md": render_readme(active, archived, fr=False),
        ROOT / "README_FR.md": render_readme(active, archived, fr=True),
        ROOT / "CATALOG.md": render_catalog(active, archived, fr=False),
        ROOT / "CATALOG_FR.md": render_catalog(active, archived, fr=True),
        ROOT / "registry.json": json.dumps(
            as_json(active, archived), indent=2, ensure_ascii=False, default=str
        )
        + "\n",
    }
    for name, payload in render_badges(active, archived).items():
        rendered[BADGES / name] = payload + "\n"

    stale: list[str] = []
    for path, content in rendered.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    if args.check:
        if stale:
            print("REFUSED: these generated files are stale:", file=sys.stderr)
            for name in stale:
                print(f"  - {name}", file=sys.stderr)
            print("\nRun: python tools/render_index.py", file=sys.stderr)
            return 1
        print(f"ok: index is current ({len(active)} active, {len(archived)} archived)")
        return 0

    print(f"wrote {len(rendered)} generated files ({len(active)} active, {len(archived)} archived)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
