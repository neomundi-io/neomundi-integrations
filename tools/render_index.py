def shield(label: str, message: str, colour: str) -> str:
    def esc(text: str) -> str:
        return text.replace("-", "--").replace("_", "__").replace(" ", "_")

    return f"https://img.shields.io/badge/{esc(label)}-{esc(message)}-{colour}?style=flat-square"


# --------------------------------------------------------------------- tables


def _row(integration: Integration, *, fr: bool) -> str:
    data = integration.data
    maturity_text, _ = MATURITY_STYLE.get(integration.maturity, (integration.maturity, "9ca3af"))
    adds = (data.get("value") or {}).get("neomundi_adds", "").strip().replace("\n", " ")
    package = integration.package_name or "—"
    # A reader who sees a package name wants the index page, not a grep.
    # Link it only where the declared version is actually installable --
    # `published_on` is the same field the install line is rendered from.
    cell = (
        f"[`{package}`](https://pypi.org/project/{package}/)"
        if integration.published_on == "pypi"
        else f"`{package}`"
    )
    published = (
        "PyPI"
        if integration.published_on == "pypi"
        else ("npm" if integration.published_on == "npm" else ("dépôt" if fr else "repo"))
    )
    return (
        f"| **[{integration.name}]({integration.rel_dir}/)** "
        f"| {cell} "
        f"| {published} "
        f"| {maturity_text} "
        f"| **{integration.evidence_level.upper()}** "
        f"| {adds} |"
    )


def _table(integrations: list[Integration], *, fr: bool) -> str:
    if not integrations:
        return "_Aucune pour l'instant._" if fr else "_None yet._"
    head = (
        "| Intégration | Paquet | Distribué par | Maturité | Preuve | Ce que NeoMundi ajoute |"
        if fr
        else "| Integration | Package | Distributed via | Maturity | Evidence | What NeoMundi adds |"
    )
    return "\n".join(
        [head, "| --- | --- | --- | --- | --- | --- |"] + [_row(i, fr=fr) for i in integrations]
    )


