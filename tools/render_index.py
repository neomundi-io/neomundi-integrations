def render_catalog(active: list[Integration], archived: list[Integration], *, fr: bool) -> str:
    other = "CATALOG.md" if fr else "CATALOG_FR.md"
    header = f"""{MARK}
# {"Catalogue des intégrations NeoMundi" if fr else "NeoMundi integration catalogue"}

[{"English" if fr else "Français"}]({other}) · [{"Index" if fr else "Index"}]({"README_FR.md" if fr else "README.md"})

{"**Registre technique.** Chaque ligne est bornée à ce qui a été réellement vérifié, à la date indiquée. Un niveau de preuve n est pas une recommandation générale de la technologie hôte, ni une garantie de production." if fr else "**Technical register.** Every row is bounded to what was actually verified, on the date given. An evidence level is not a general endorsement of the host technology, nor a production-readiness guarantee."}

---
"""
    sections = [header]
    for integration in active + archived:
        sections.append(_catalog_entry(integration, fr=fr))

    sections.append(
        f"\n## {'Niveaux de preuve' if fr else 'Evidence levels'}\n\n"
        + "\n".join(f"- **{k.upper()}** — {v}" for k, v in EVIDENCE_LEVELS.items())
        + "\n"
    )
    return "\n".join(sections)


def _catalog_entry(integration: Integration, *, fr: bool) -> str:
    d = integration.data
    tech = d.get("technology") or {}
    comp = d.get("compatibility") or {}
    target = comp.get("target") or {}
    sdk = comp.get("neomundi_sdk") or {}
    ev = d.get("evidence") or {}
    value = d.get("value") or {}
    billing = d.get("billing") or {}

    state = (
        " · **ARCHIVÉE**"
        if (integration.archived and fr)
        else (" · **ARCHIVED**" if integration.archived else "")
    )
    lines = [f"\n## {integration.name}{state}\n"]
    lines.append(f"> {tech.get('what_it_is', '').strip()}\n")

    if fr:
        lines.append("| | |\n| --- | --- |")
        lines.append(
            f"| Paquet | `{integration.package_name}` {integration.data.get('package', {}).get('version', '')} |"
        )
        lines.append(f"| Installation | `{integration.install_line}` |")
        lines.append(f"| Maturité | {integration.maturity} |")
        lines.append(
            f"| Niveau de preuve | **{integration.evidence_level.upper()}** — {EVIDENCE_LEVELS.get(integration.evidence_level, '')} |"
        )
        lines.append(f"| Python | {', '.join(comp.get('python', []))} |")
        lines.append(f"| Plateformes | {', '.join(comp.get('platforms', []))} |")
        lines.append(
            f"| Cible vérifiée | `{target.get('name', '')}` {target.get('verified', '')} (bornes {target.get('min', '?')} → {target.get('max', '?')}) |"
        )
        lines.append(
            f"| SDK NeoMundi | ≥ {sdk.get('min', '?')}, vérifié {sdk.get('verified', '?')} |"
        )
        lines.append(
            f"| `measurement_version` vérifiée | **{comp.get('measurement_version_verified', '—')}** |"
        )
        lines.append(f"| Tests hors ligne | {ev.get('offline_tests', '—')} |")
        lines.append(
            f"| Observations réelles | {ev.get('real_observations', '—')}, dont {ev.get('observations_verified_persisted', '—')} relues persistées |"
        )
        lines.append(f"| Facturée | {'oui' if billing.get('metered') else 'non'} |")
        lines.append(
            f"| Livrée | {d.get('delivered', '—')} · dernière vérification {d.get('last_verified', '—')} |"
        )
        lines.append("\n**Ce que la technologie garde.** " + value.get("host_keeps", "").strip())
        lines.append("\n**Ce que NeoMundi ajoute.** " + value.get("neomundi_adds", "").strip())
        if value.get("complements_not_replaces"):
            lines.append(
                "\n**Complète, ne remplace pas :** "
                + ", ".join(value["complements_not_replaces"])
                + "."
            )
        lines.append("\n**Ce qu'elle refuse de faire.**\n")
        for refusal in d.get("refusals", []):
            lines.append(f"- {refusal}")
        if billing.get("note"):
            lines.append(f"\n🔴 {billing['note'].strip()}")
        links = d.get("links") or {}
        nav = " · ".join(
            f"[{label}]({integration.rel_dir}/{links[key]})"
            for key, label in [
                ("readme_fr", "Guide"),
                ("limitations", "Limites"),
                ("value", "Valeur et ROI"),
                ("notebook", "Notebook"),
                ("examples", "Exemples"),
                ("evidence", "Preuves"),
                ("mission_report", "Rapport de mission"),
                ("changelog", "Journal"),
            ]
            if key in links
        )
        lines.append(f"\n{nav}\n")
    else:
        lines.append("| | |\n| --- | --- |")
        lines.append(
            f"| Package | `{integration.package_name}` {integration.data.get('package', {}).get('version', '')} |"
        )
        lines.append(f"| Install | `{integration.install_line}` |")
