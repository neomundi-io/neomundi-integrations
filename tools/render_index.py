#!/usr/bin/env python3
"""Render README, CATALOG and the badge endpoints from the registry.

Nothing here is written by hand, in either language. ``index.yml`` runs this
with ``--check`` on every pull request and fails if the committed files
differ from a fresh render, so the index cannot drift from the integrations
it describes.

    python tools/render_index.py           # write
    python tools/render_index.py --check   # fail if stale
"""

